#!/usr/bin/env python3
"""Generate src/apps/hinto/i18n/help.ts from the app's in-app Help (HelpView.swift) and its Japanese translations
(tools/l10n/ja.py), so the website's FAQ says exactly what the app says. Uses the branches for
AICardMaker.claudeAvailable == false (the Claude card maker is switched off).

Usage: python3 scripts/hinto/sync-help.py [path to the Hinto app repo, default ../Hinto-ios]
"""
import json, os, re, sys

app = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "..", "..", "Hinto-ios")
src = open(os.path.join(app, "Hinto/Features/Settings/HelpView.swift"), encoding="utf-8").read()
sys.path.insert(0, os.path.join(app, "tools/l10n"))
import ja  # noqa: E402

body = src[src.index("static let all"):]
# Keep only the "Claude off" side of `AICardMaker.claudeAvailable ? A : B`.
body = re.sub(r"AICardMaker\.claudeAvailable\s*\?\s*Item\(.*?\"\)\s*:\s*Item\(", "Item(", body, flags=re.S)
body = re.sub(r"AICardMaker\.claudeAvailable\s*\?\s*Item\(.*?\"\)\s*:\s*Item\(", "Item(", body, flags=re.S)

topics = []
for m in re.finditer(r'HelpTopic\(title: "((?:[^"\\]|\\.)*)", icon: "([^"]*)", items: \[(.*?)\]\)', body, re.S):
    title, icon, items_src = m.groups()
    items = re.findall(r'question: "((?:[^"\\]|\\.)*)",\s*answer: "((?:[^"\\]|\\.)*)"', items_src, re.S)
    topics.append((title, icon, items))

def tr(s):
    s = s.replace('\\"', '"')
    if s not in ja.T:
        raise SystemExit(f"no Japanese for: {s}")
    return ja.T[s]

out = {"en": [], "ja": []}
for title, icon, items in topics:
    for lang in ("en", "ja"):
        t = (lambda s: s.replace('\\"', '"')) if lang == "en" else tr
        out[lang].append({"title": t(title), "icon": icon,
                          "items": [{"q": t(q), "a": t(a)} for q, a in items]})

path = os.path.join(os.path.dirname(__file__), "..", "..", "src/apps/hinto/i18n/help.ts")
with open(path, "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/sync-help.py from the app's in-app Help. Don't edit by hand; rerun the script.\n")
    f.write("export type HelpTopic = { title: string; icon: string; items: { q: string; a: string }[] };\n")
    f.write("export const help: Record<'en' | 'ja', HelpTopic[]> = ")
    f.write(json.dumps(out, ensure_ascii=False, indent=2))
    f.write(";\n")
print(f"{len(topics)} topics, {sum(len(t[2]) for t in topics)} questions -> src/apps/hinto/i18n/help.ts")
